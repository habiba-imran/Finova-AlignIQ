import { expect, test } from '@playwright/test'

test('Micro demo runs real validation, displays supplied choices and exports the exact DRAFT', async ({ page, context }, testInfo) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/', { waitUntil: 'networkidle' })
  await page.getByRole('navigation', { name: 'Review purpose' }).getByRole('button', { name: /MICRO/ }).click()
  await page.screenshot({ path: testInfo.outputPath('micro-intake.png'), fullPage: true })
  const requests: string[] = []; page.on('request', r => requests.push(r.url()))
  const loaded = page.waitForResponse(r => r.url().endsWith('/api/v1/development/attachment-demo/input'))
  await page.getByRole('button', { name: 'Load Finova attachment demo' }).click()
  const inputResponse = await loaded, input = await inputResponse.json()
  expect(inputResponse.status()).toBe(200)
  expect(inputResponse.headers()['cache-control']).toBe('no-store')
  expect(inputResponse.request().postDataJSON()).toEqual({})
  await expect(page.getByRole('textbox', { name: 'Raw TMT text' })).toHaveValue(input.parsed.raw_text)
  expect(await page.getByLabel('Raw text preview').textContent()).toBe(input.parsed.raw_text)
  const pending = page.waitForResponse(r => r.url().endsWith('/api/v1/development/attachment-demo/draft'))
  await page.getByRole('button', { name: 'Run Attachment Review' }).click()
  const response = await pending, draft = await response.json()
  expect(response.status()).toBe(200); expect(response.request().postDataJSON()).toEqual({})
  expect(draft.evidence_domain).toBe('TEST_ONLY'); expect(draft.provider_attempts).toBe(0)
  expect(draft.engine_review.evaluations).toHaveLength(96)
  expect(draft.engine_review.evaluations.filter((e: { execution: string }) => e.execution === 'DISABLED')).toHaveLength(27)
  const article = page.getByRole('article', { name: 'Attachment review draft' })
  await expect(article).toBeVisible()
  await expect(article.getByRole('heading', { name: 'Attachment review draft' })).toBeFocused()
  const table = article.getByRole('table')
  await expect(table.getByText('Supplied candidate', { exact: true })).toHaveCount(2)
  for (const label of ['Supplied alternative', 'Supplied no attachment', 'Unknown', 'Withheld']) await expect(table.getByText(label, { exact: true })).toBeVisible()
  await table.getByText('Details & provenance · row 1').click()
  await expect(table.getByText('Supplied dimensions: 2.000 × 1.250 × 0.500 mm', { exact: true })).toBeVisible()
  await expect(table.getByText(/Evidence: FINOVA-ATTACHMENTS-1:.*rows\/candidate-a/)).toBeVisible()
  await table.getByText('Details & provenance · row 1').click()
  await article.getByRole('button', { name: 'Copy attachment DRAFT' }).click()
  expect((await page.evaluate(() => navigator.clipboard.readText())).replaceAll('\r\n', '\n')).toBe(draft.export_text)
  const downloadPending = page.waitForEvent('download')
  await article.getByRole('button', { name: 'Download attachment DRAFT (TXT)' }).click()
  const download = await downloadPending, chunks: Buffer[] = []
  expect(download.suggestedFilename()).toBe(`finova-attachments-draft-${draft.report_id.slice(0, 12)}.txt`)
  for await (const chunk of (await download.createReadStream())!) chunks.push(Buffer.from(chunk))
  expect(Buffer.concat(chunks).toString('utf8')).toBe(draft.export_text)
  expect(draft.export_text).toContain('NOT_INDICATED; origin: SUPPLIED_SYNTHETIC')
  expect(draft.export_text).toContain('RULE EVALUATION LEDGER')
  expect(draft.export_text).toContain('DRAFT — Requires Orthodontist Review')
  expect(requests.filter(url => !url.startsWith('blob:'))).toEqual([
    'http://127.0.0.1:5173/api/v1/development/attachment-demo/input', 'http://127.0.0.1:5173/api/v1/development/attachment-demo/draft',
  ])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0])
  await article.screenshot({ path: testInfo.outputPath('micro-draft.png') })
  await page.getByRole('textbox', { name: 'Raw TMT text' }).fill(input.parsed.raw_text + 'changed')
  await expect(article).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: /I confirm/ })).not.toBeChecked()
  expect(errors).toEqual([])
})

test('ordinary Micro input never derives an attachment or geometry from movement size', async ({ page }) => {
  await page.goto('/', { waitUntil: 'networkidle' })
  await page.getByRole('navigation', { name: 'Review purpose' }).getByRole('button', { name: /MICRO/ }).click()
  const requests: string[] = []; page.on('request', r => requests.push(r.url()))
  const raw = '# SYNTHETIC UnknownVendor\nTooth\tRotation (deg)\n13\t999.000 M\n14\t-\n'
  await page.getByRole('textbox', { name: 'Raw TMT text' }).fill(raw)
  await page.getByRole('checkbox', { name: /I confirm/ }).check()
  await page.getByRole('button', { name: 'Parse Table', exact: true }).click()
  const pending = page.waitForResponse(r => r.url().endsWith('/api/v1/attachments/draft'))
  await page.getByRole('button', { name: 'Run Attachment Review' }).click()
  const response = await pending, draft = await response.json()
  expect(response.request().postDataJSON().raw_text).toBe(raw)
  expect(draft.evidence_domain).toBe('UNVERIFIED')
  expect(draft.entries.map((e: { result_type: string }) => e.result_type)).toEqual(['UNKNOWN', 'WITHHELD'])
  expect(draft.entries.every((e: { design: unknown; placement: unknown }) => e.design === null && e.placement === null)).toBe(true)
  const article = page.getByRole('article', { name: 'Attachment review draft' })
  await expect(article.getByText('Unverified input — attachment recommendations unavailable.', { exact: true })).toBeVisible()
  await expect(article.getByRole('table').getByText('Supplied no attachment', { exact: true })).toHaveCount(0)
  expect(requests).toEqual(['http://127.0.0.1:5173/api/v1/tmt/parse', 'http://127.0.0.1:5173/api/v1/attachments/draft'])
  expect(await page.getByLabel('Raw text preview').textContent()).toBe(raw)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('Micro error retains input and explicit retry; purpose switch invalidates the result', async ({ page }) => {
  await page.goto('/')
  const nav = page.getByRole('navigation', { name: 'Review purpose' })
  await nav.getByRole('button', { name: /MICRO/ }).click()
  await page.getByRole('button', { name: 'Load Finova attachment demo' }).click()
  const run = page.getByRole('button', { name: 'Run Attachment Review' }); await expect(run).toBeVisible()
  const raw = await page.getByRole('textbox', { name: 'Raw TMT text' }).inputValue()
  let calls = 0
  await page.route('**/api/v1/development/attachment-demo/draft', async route => {
    calls++; if (calls === 1) await route.fulfill({ status: 503, json: { detail: 'Unavailable' } }); else await route.continue()
  })
  await run.click(); await expect(page.getByRole('alert')).toContainText('original text is preserved')
  expect(calls).toBe(1); await expect(page.getByRole('textbox', { name: 'Raw TMT text' })).toHaveValue(raw)
  await run.click(); await expect(page.getByRole('article', { name: 'Attachment review draft' })).toBeVisible()
  await nav.getByRole('button', { name: /NANO/ }).click()
  await expect(page.getByRole('button', { name: 'Load Finova sequencing demo' })).toBeVisible()
  await expect(page.getByRole('article', { name: 'Attachment review draft' })).toHaveCount(0)
  await nav.getByRole('button', { name: /MACRO/ }).click()
  await expect(page.getByRole('button', { name: 'Load Finova planning demo' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Raw TMT text' })).toHaveValue(raw)
})
