import { expect, test } from '@playwright/test'

test('explicit draft review uses the real API, abstains on vendor claims and preserves raw input', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const raw = '# SYNTHETIC\n\nTooth\tRotation (deg)\tExtrusion (mm)\n 13 \t−1.2300 M\t0.00 E  \n14\t\t—\n'
  const input = page.getByRole('textbox', { name: 'Raw TMT text' })
  await input.fill(raw)
  await expect(page.getByRole('combobox', { name: /Source/ })).toHaveCount(0)
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: 'Parse Table', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Structured lexical preview' })).toBeVisible()
  await page.getByLabel('Requested assessment', { exact: false }).selectOption('ATTACHMENTS')
  const pending = page.waitForResponse(r => r.url().endsWith('/api/v1/tmt/observations'))
  await page.getByRole('button', { name: 'Create draft review', exact: true }).click()
  const response = await pending
  expect(response.status()).toBe(200)
  expect(response.headers()['cache-control']).toBe('no-store')
  expect(response.request().postDataJSON().raw_text).toBe(raw)
  const report = await response.json()
  expect(report.review_status).toBe('DRAFT')
  expect(report.evidence_domain).toBe('UNVERIFIED')
  expect(report.clinical_analysis_enabled).toBe(false)
  expect(report.coverage.eligible_positions).toBe(0)
  expect(report.engine_version).toBe('0.5.0')
  expect(report.evaluations).toHaveLength(96)
  expect(report.evaluations.filter((e: { execution: string }) => e.execution === 'DISABLED')).toHaveLength(27)
  expect(report.findings.every((f: { observed_measurements: unknown[] }) => f.observed_measurements.length === 0)).toBe(true)
  const results = page.getByLabel('Draft review results')
  await expect(results).toBeVisible()
  await expect(results.getByText('DRAFT — Requires Orthodontist Review', { exact: true })).toBeVisible()
  await results.getByText('Rule evaluation ledger (96 rules)').click()
  await expect(results.getByText('R01 · DISABLED', { exact: true })).toBeVisible()
  await expect(results.getByText('D16 · CONTEXT_REQUIRED', { exact: true })).toBeVisible()
  await expect(results.getByText(/No authorized descriptive movement findings/)).toBeVisible()
  await expect(input).toHaveValue(raw)
  expect(await page.getByLabel('Raw text preview').textContent()).toBe(raw)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0])
  await testInfo.attach('phase2a-draft-unverified', { body: await results.screenshot(), contentType: 'image/png' })
  await input.fill(raw + '\n')
  await expect(results).toHaveCount(0)
  await expect(page.getByRole('checkbox')).not.toBeChecked()
  expect(errors).toEqual([])
})
