import { expect, test } from '@playwright/test'

test('Nano demo runs real stages/guards, separates arch and side notes, and exports exact DRAFT', async ({ page, context }, testInfo) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/', { waitUntil: 'networkidle' })
  const nano = page.getByRole('navigation', { name: 'Review purpose' }).getByRole('button', { name: /NANO/ })
  await nano.focus(); await page.keyboard.press('Enter'); await expect(nano).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: testInfo.outputPath('nano-intake.png'), fullPage: true })
  const requests: string[] = []; page.on('request', r => requests.push(r.url()))
  const loaded = page.waitForResponse(r => r.url().endsWith('/api/v1/development/sequencer-demo/input'))
  await page.getByRole('button', { name: 'Load Finova sequencing demo' }).click()
  const inputResponse = await loaded, input = await inputResponse.json()
  expect(inputResponse.status()).toBe(200); expect(inputResponse.headers()['cache-control']).toBe('no-store')
  expect(inputResponse.request().postDataJSON()).toEqual({})
  await expect(page.getByRole('textbox', { name: 'Raw TMT text' })).toHaveValue(input.parsed.raw_text)
  expect(await page.getByLabel('Raw text preview').textContent()).toBe(input.parsed.raw_text)
  const pending = page.waitForResponse(r => r.url().endsWith('/api/v1/development/sequencer-demo/draft'))
  await page.getByRole('button', { name: 'Run Sequencing Review' }).click()
  const response = await pending, report = await response.json()
  expect(response.status()).toBe(200); expect(response.request().postDataJSON()).toEqual({})
  expect(report.engine_review.evaluations).toHaveLength(96)
  expect(report.engine_review.evaluations.filter((e: { execution: string }) => e.execution === 'DISABLED')).toHaveLength(27)
  expect(report.engine_review.evaluations.find((e: { rule_id: string }) => e.rule_id === 'G15').status).toBe('OBSERVED')
  expect(report.engine_review.evaluations.find((e: { rule_id: string }) => e.rule_id === 'N07').status).toBe('NOT_APPLICABLE')
  expect(report.provider_attempts).toBe(0); expect(report.stage_inspection.movement_binding).toBe('NO_STAGE_MOVEMENT_BINDING')
  const article = page.getByRole('article', { name: 'Sequencing review draft' })
  await expect(article.getByRole('heading', { name: 'Sequencing review draft' })).toBeFocused()
  await expect(article.getByText('SYNTHETIC DEMONSTRATION — NOT CLINICAL ADVICE', { exact: true })).toBeVisible()
  for (const title of ['Upper-arch sequencing', 'Lower-arch sequencing', 'Segments & tooth groups', 'Right-side anchorage', 'Left-side anchorage', 'Unavailable assessments']) await expect(article.getByRole('region', { name: title })).toBeVisible()
  await expect(article.getByRole('region', { name: 'Right-side anchorage' })).toContainText('Supplied fictional right-side anchorage note')
  await expect(article.getByRole('region', { name: 'Left-side anchorage' })).toContainText('Supplied fictional left-side anchorage note')
  const upper = article.getByRole('region', { name: 'Upper-arch sequencing' })
  await upper.getByText('Evidence & source details', { exact: true }).click()
  await expect(upper.getByText(/Supplied stage window IDs: DEMO_U_BASE/)).toBeVisible()
  await expect(upper.getByText(/1.2300 D/)).toBeVisible()
  await upper.getByText('Evidence & source details', { exact: true }).click()
  await article.getByRole('button', { name: 'Copy sequencing DRAFT' }).click()
  expect((await page.evaluate(() => navigator.clipboard.readText())).replaceAll('\r\n', '\n')).toBe(report.export_text)
  const downloadPending = page.waitForEvent('download')
  await article.getByRole('button', { name: 'Download sequencing DRAFT (TXT)' }).click()
  const download = await downloadPending, chunks: Buffer[] = []
  expect(download.suggestedFilename()).toBe(`finova-sequencing-draft-${report.report_id.slice(0, 12)}.txt`)
  for await (const chunk of (await download.createReadStream())!) chunks.push(Buffer.from(chunk))
  expect(Buffer.concat(chunks).toString('utf8')).toBe(report.export_text)
  expect(report.export_text).toContain('SYNTHETIC DEMONSTRATION — NOT CLINICAL ADVICE')
  expect(report.export_text).toContain('RULE EVALUATION LEDGER')
  expect(requests.filter(url => !url.startsWith('blob:'))).toEqual(['http://127.0.0.1:5173/api/v1/development/sequencer-demo/input', 'http://127.0.0.1:5173/api/v1/development/sequencer-demo/draft'])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0])
  await article.screenshot({ path: testInfo.outputPath('nano-draft.png') })
  await page.getByRole('textbox', { name: 'Raw TMT text' }).fill(input.parsed.raw_text + 'changed')
  await expect(article).toHaveCount(0)
  await expect(page.getByRole('checkbox', { name: /I confirm/ })).not.toBeChecked()
  expect(errors).toEqual([])
})

test('normal Nano input preserves zero/missing values while withholding sequence and anchorage', async ({ page }) => {
  await page.goto('/', { waitUntil: 'networkidle' })
  await page.getByRole('navigation', { name: 'Review purpose' }).getByRole('button', { name: /NANO/ }).click()
  const requests: string[] = []; page.on('request', r => requests.push(r.url()))
  const raw = '# SYNTHETIC ClinCheck-style unverified\nTooth\tRotation (deg)\tExtrusion (mm)\n13\t999.000 M\t0.000 E\n14\t-\t-\n'
  await page.getByRole('textbox', { name: 'Raw TMT text' }).fill(raw)
  await page.getByRole('checkbox', { name: /I confirm/ }).check()
  await page.getByRole('button', { name: 'Parse Table', exact: true }).click()
  const pending = page.waitForResponse(r => r.url().endsWith('/api/v1/sequencing/draft'))
  await page.getByRole('button', { name: 'Run Sequencing Review' }).click()
  const response = await pending, report = await response.json()
  expect(response.request().postDataJSON().raw_text).toBe(raw)
  expect(report.evidence_domain).toBe('UNVERIFIED'); expect(report.provider_attempts).toBe(0)
  expect(report.stage_inspection.status).toBe('MISSING'); expect(report.stage_inspection.records).toEqual([])
  expect(report.fictional_arches).toEqual([]); expect(report.fictional_segments).toEqual([])
  expect(report.parsed.measurements.map((m: { numeric_status: string }) => m.numeric_status)).toEqual(['PARSED', 'EXPLICIT_ZERO', 'MISSING', 'MISSING'])
  const article = page.getByRole('article', { name: 'Sequencing review draft' })
  await expect(article.getByRole('heading', { name: 'Actual stage data unavailable' })).toBeVisible()
  await expect(article.getByRole('region', { name: 'Right-side anchorage' })).toContainText('Unknown')
  await expect(article.getByRole('region', { name: 'Left-side anchorage' })).toContainText('Unknown')
  await expect(article.getByText('Supplied fictional statement', { exact: true })).toHaveCount(0)
  expect(requests).toEqual(['http://127.0.0.1:5173/api/v1/tmt/parse', 'http://127.0.0.1:5173/api/v1/sequencing/draft'])
  expect(await page.getByLabel('Raw text preview').textContent()).toBe(raw)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('Nano error permits explicit retry; navigation preserves input and clears its draft', async ({ page }) => {
  await page.goto('/')
  const nav = page.getByRole('navigation', { name: 'Review purpose' })
  await nav.getByRole('button', { name: /NANO/ }).click()
  await page.getByRole('button', { name: 'Load Finova sequencing demo' }).click()
  const run = page.getByRole('button', { name: 'Run Sequencing Review' }); await expect(run).toBeVisible()
  const raw = await page.getByRole('textbox', { name: 'Raw TMT text' }).inputValue()
  let calls = 0
  await page.route('**/api/v1/development/sequencer-demo/draft', async route => {
    calls++; if (calls === 1) await route.fulfill({ status: 503, json: { detail: 'Unavailable' } }); else await route.continue()
  })
  await run.click(); await expect(page.getByRole('alert')).toContainText('original text is preserved')
  expect(calls).toBe(1)
  await run.click(); await expect(page.getByRole('article', { name: 'Sequencing review draft' })).toBeVisible()
  for (const purpose of ['MICRO', 'MACRO']) {
    await nav.getByRole('button', { name: new RegExp(purpose) }).click()
    await expect(page.getByRole('textbox', { name: 'Raw TMT text' })).toHaveValue(raw)
    await expect(page.getByRole('article', { name: 'Sequencing review draft' })).toHaveCount(0)
  }
  await expect(page.getByRole('button', { name: 'Load Finova planning demo' })).toBeVisible()
})
